"""Write simulation vectors for the aegis_pqc testbenches (tb/vectors/).

All expected values come from hw/model (keccak.py, ntt.py: the FIPS 202 /
203 / 204 references; ntt_hw.py only for the modmul unit test and the
expected cycle counts). Files are read by the testbenches with $readmemh.

  python gen_vectors.py [--seed S] [--keccak N] [--ntt N] [--modmul N]
"""

import argparse
import os
import random
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "model"))

import keccak            # noqa: E402
import ntt               # noqa: E402
import ntt_hw            # noqa: E402

OUT = os.path.join(HERE, "vectors")
LANE_BASE = 0x38          # must match rtl/aegis_pqc.v and sw/aegis_pqc_regs.h
KECCAK_CYCLES = 24


def write_hex(name, values, digits):
    with open(os.path.join(OUT, name), "w") as f:
        for v in values:
            f.write(f"{v:0{digits}X}\n")


def keccak_vectors(rng, n):
    states = [[0] * 25, [keccak.MASK64] * 25]
    states += [[rng.getrandbits(64) for _ in range(25)] for _ in range(n - len(states))]
    outs = [keccak.keccak_f1600(s) for s in states]
    assert outs[0][0] == keccak.ZERO_STATE_LANE0
    write_hex("keccak_in.hex", [v for s in states for v in s], 16)
    write_hex("keccak_out.hex", [v for s in outs for v in s], 16)
    return len(states)


def ntt_vectors(rng, mode, n):
    q = ntt.modulus(mode)
    special = [
        [0] * 256,
        [q - 1] * 256,
        [1] + [0] * 255,
        [0] * 255 + [q - 1],
        [i % q for i in range(256)],
        [(q - 1) if i & 1 else 0 for i in range(256)],
    ]
    count = 0
    for inverse in (False, True):
        vecs = [list(v) for v in special]
        vecs += [[rng.randrange(q) for _ in range(256)] for _ in range(n - len(vecs))]
        outs = [ntt.transform(mode, inverse, v) for v in vecs]
        tag = f"ntt_{mode}_{'inv' if inverse else 'fwd'}"
        write_hex(tag + "_in.hex", [c for v in vecs for c in v], 6)
        write_hex(tag + "_out.hex", [c for v in outs for c in v], 6)
        count = len(vecs)
    return count


def modmul_vectors(rng, n):
    """Lines: {mode, a, b, a*b mod q}, 24 bits each. Grouped by mode."""
    rows = []
    cover = {}
    for mbit, mode in ((0, "kem"), (1, "dsa")):
        q = ntt_hw.Q[mode]
        edge = [0, 1, 2, 3, (q - 1) // 2, (q + 1) // 2, q - 3, q - 2, q - 1]
        pairs = [(a, b) for a in edge for b in edge]
        pairs += [(rng.randrange(q), rng.randrange(q)) for _ in range(n)]
        # Products that need both conditional subtractions. They exist only
        # for ML-KEM; for ML-DSA, r < 1.51q for every product (ntt_hw.py).
        if mode == "kem":
            pairs += ntt_hw.pairs_needing_two_subtractions(mode, 512)
        hits = [0, 0, 0]
        for a, b in pairs:
            hits[ntt_hw.barrett_raw(a * b, mode) // q] += 1
        cover[mode] = hits
        for a, b in pairs:
            rows.append((mbit << 72) | (a << 48) | (b << 24) | ((a * b) % q))
    write_hex("modmul.hex", rows, 24)
    return len(rows), cover


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--seed", type=int, default=20261116)
    ap.add_argument("--keccak", type=int, default=256)
    ap.add_argument("--ntt", type=int, default=64)
    ap.add_argument("--modmul", type=int, default=20000)
    args = ap.parse_args()
    rng = random.Random(args.seed)
    os.makedirs(OUT, exist_ok=True)

    nk = keccak_vectors(rng, args.keccak)
    nn = ntt_vectors(rng, "kem", args.ntt)
    nn2 = ntt_vectors(rng, "dsa", args.ntt)
    assert nn == nn2
    nm, cover = modmul_vectors(rng, args.modmul)

    with open(os.path.join(OUT, "params.svh"), "w") as f:
        f.write("// GENERATED by hw/tb/gen_vectors.py -- do not edit.\n")
        f.write(f"localparam integer NK            = {nk};\n")
        f.write(f"localparam integer NV            = {nn};\n")
        f.write(f"localparam integer NM            = {nm};\n")
        f.write(f"localparam [7:0]   LANE_BASE     = 8'h{LANE_BASE:02X};\n")
        f.write(f"localparam integer KECCAK_CYC    = {KECCAK_CYCLES};\n")
        f.write(f"localparam integer NTT_CYC_KEM   = {ntt_hw.cycles('kem')};\n")
        f.write(f"localparam integer NTT_CYC_DSA   = {ntt_hw.cycles('dsa')};\n")
    print(f"gen_vectors.py: seed {args.seed}: {nk} Keccak states, {nn} vectors per NTT mode/direction, "
          f"{nm} modmul rows (reduction branch hits r<q / q<=r<2q / r>=2q: "
          f"KEM {cover['kem']}, DSA {cover['dsa']}) -> {os.path.normpath(OUT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
