"""Release hygiene of the repository, on the files git tracks:

  spdx      every source file of this project (C, Python, shell, CMake, make, YAML, linker scripts, systemd units,
            Dockerfiles) names its licence with an SPDX-License-Identifier line in its first 15 lines. Third-party
            files that carry their own copyright notice are listed, not changed; a few files are exempt, each with
            the reason below.
  secrets   no private key, access token, verifier or device state, or local bench configuration is tracked.

  tools/check_release.py            both checks; exit 1 if either fails
  tools/check_release.py --list     also list the third-party and exempt files
"""
import argparse
import fnmatch
import os
import re
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))

SOURCE = ("*.c", "*.h", "*.S", "*.py", "*.sh", "*.cmake", "*.yaml", "*.yml", "*.ld", "*.service", "*.timer",
          "CMakeLists.txt", "Makefile", "Dockerfile", "Dockerfile.*", "*.dockerfile", "bench.env.example")
SPDX = re.compile(r"SPDX-License-Identifier: \S+")
THIRD_PARTY = re.compile(r"Copyright (\(c\) )?\d{4}.*(Arm|ARM|NXP|STMicroelectronics|Cypress|Linaro|Microchip|"
                         r"Xilinx|AMD|Nordic|Zephyr|Infineon)")
# path pattern -> why it carries no SPDX line of this project
EXEMPT = {
    "tests/fuzz/seeds/*": "fuzzer seed (binary input data)",
    "tests/fuzz/stm32/seeds/*": "fuzzer seed (binary input data)",
    "endpoints/zybo/aegis_linux_prover.py": "deployed to the bench as it is; the software-trust profile measures this "
                                            "file, so a changed byte changes the reference value in the bench policy",
    "endpoints/*/tfm/*/*.yaml": "TF-M partition manifest (JSON read by TF-M's build); kept byte for byte as built",
    "endpoints/stm32h573/tfm-aegis-partition/*.yaml": "TF-M partition manifest (JSON read by TF-M's build); kept "
                                                      "byte for byte as built",
    "docs/diagrams/console.yaml": "generated by tools/make_console_figures.py",
    "docs/diagrams/wave-keccak.yaml": "generated by hw/tb/make_wave.sh",
    "docs/diagrams/wave-sponge-dma.yaml": "generated by hw/tb/make_wave_dma.sh",
}

# what must never be tracked
SECRET_CONTENT = [
    (re.compile(r"-----BEGIN (RSA |EC |DSA |OPENSSH |ENCRYPTED )?PRIVATE KEY-----"), "a PEM private key"),
    (re.compile(r"\bAKIA[0-9A-Z]{16}\b"), "an AWS access key id"),
    (re.compile(r"\bgh[pousr]_[A-Za-z0-9]{36}\b|\bgithub_pat_[A-Za-z0-9_]{40,}"), "a GitHub token"),
    (re.compile(r"\bxox[abprs]-[A-Za-z0-9-]{10,}"), "a Slack token"),
    (re.compile(r"\"(sk|secret_key|private_key|seed)\"\s*:\s*\"[0-9a-fA-F]{64,}\""), "a secret key in JSON"),
]
SECRET_NAMES = [
    ("bench.env", "the local bench configuration (bench.env.example is the template)"),
    ("*identity.json", "a verifier identity (holds or wraps its secret key)"),
    ("*identity.tpm.json", "a verifier identity sealed to a TPM"),
    ("*.session", "a session key"),
    ("*id_rsa*", "an SSH key"), ("*id_ed25519*", "an SSH key"), ("*id_ecdsa*", "an SSH key"),
    ("*.p12", "a key store"), ("*.pfx", "a key store"), ("*.jks", "a key store"),
    ("*.netrc", "credentials"), (".env", "environment secrets"),
]
# Published keys that look like secrets but are not: none at present. Each entry: path -> why it is public.
SECRET_ALLOWED = {}


SKIP_DIRS = {".git", ".venv", "logs", "build", "backups", "__pycache__", "host/enrolled"}


def tracked():
    """The files git tracks; without git (a copy such as the evaluation container's) every file but the ignored
    kinds (.gitignore: logs, builds, the venv, local state)."""
    try:
        out = subprocess.run(["git", "-C", ROOT, "ls-files", "-z"], capture_output=True, check=True).stdout
        return [p for p in out.decode().split("\0") if p]
    except (OSError, subprocess.CalledProcessError):
        pass
    files = []
    for d, dirs, names in os.walk(ROOT):
        rel = os.path.relpath(d, ROOT)
        dirs[:] = sorted(x for x in dirs if x not in SKIP_DIRS and os.path.normpath(os.path.join(rel, x)) not in
                         SKIP_DIRS and not x.startswith("build"))
        for n in sorted(names):
            if not n.endswith((".pyc",)) and n != "bench.env":
                files.append(os.path.normpath(os.path.join(rel, n)))
    return files


def match(path, patterns):
    name = os.path.basename(path)
    return any(fnmatch.fnmatch(path, p) or fnmatch.fnmatch(name, p) for p in patterns)


def head(path, n):
    try:
        with open(os.path.join(ROOT, path), "rb") as f:
            data = f.read(8192)
    except OSError:
        return None
    if b"\0" in data:
        return None
    return "\n".join(data.decode("utf-8", "replace").split("\n")[:n])


def check_spdx(files):
    missing, third, exempt = [], [], []
    for p in files:
        if not match(p, SOURCE):
            continue
        why = next((w for pat, w in EXEMPT.items() if fnmatch.fnmatch(p, pat)), None)
        if why:
            exempt.append((p, why))
            continue
        text = head(p, 15)
        if text is None:
            continue
        if SPDX.search(text):
            continue
        if THIRD_PARTY.search(head(p, 30) or ""):
            third.append(p)
            continue
        missing.append(p)
    return missing, third, exempt


def check_secrets(files):
    found = []
    for p in files:
        if p in SECRET_ALLOWED:
            continue
        for pat, what in SECRET_NAMES:
            if fnmatch.fnmatch(os.path.basename(p), pat):
                found.append((p, what))
        try:
            with open(os.path.join(ROOT, p), "rb") as f:
                data = f.read(4 << 20)
        except OSError:
            continue
        if b"\0" in data[:8192]:
            continue
        text = data.decode("utf-8", "replace")
        for pat, what in SECRET_CONTENT:
            m = pat.search(text)
            if m:
                found.append(("%s:%d" % (p, text.count("\n", 0, m.start()) + 1), what))
    return found


def main(argv=None):
    ap = argparse.ArgumentParser(description="SPDX headers and secrets in the tracked files")
    ap.add_argument("--list", action="store_true", help="list the third-party and exempt files too")
    a = ap.parse_args(argv)
    files = tracked()
    missing, third, exempt = check_spdx(files)
    secrets = check_secrets(files)
    for p in missing:
        print("NO SPDX  %s" % p)
    for p, what in secrets:
        print("SECRET   %s: %s" % (p, what))
    if a.list:
        for p in third:
            print("third-party (own notice)  %s" % p)
        for p, why in exempt:
            print("exempt  %s: %s" % (p, why))
    print("%d tracked files: %d without an SPDX line, %d third-party with their own notice, %d exempt; %d secrets"
          % (len(files), len(missing), len(third), len(exempt), len(secrets)))
    return 1 if missing or secrets else 0


if __name__ == "__main__":
    sys.exit(main())
