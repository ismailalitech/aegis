#!/usr/bin/env python3
"""Write the gateway's ML-DSA-65 public key as a C header for the STM32 secure partition, so the
partition can verify credentials (mutual authentication). Source: the gateway's identity record.
  gen_gateway_pin.py [GATEWAY_HOST]   ->  endpoints/stm32h573/tfm-aegis-partition/gateway_pk.h
"""
import hashlib
import json
import os
import subprocess
import sys

host = sys.argv[1] if len(sys.argv) > 1 else os.environ.get("GATEWAY") or sys.exit("usage: gen_gateway_pin.py <gateway-host> (or set GATEWAY)")
rec = json.loads(subprocess.run(["ssh", "-o", "BatchMode=yes", "root@" + host, "cat /var/lib/aegis/identity.json"],
                                check=True, capture_output=True, text=True).stdout)
pk = bytes.fromhex(rec["body"]["pk"])
assert len(pk) == 1952
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "endpoints", "stm32h573",
                   "tfm-aegis-partition", "gateway_pk.h")
with open(out, "w") as f:
    f.write("/* Generated by tools/gen_gateway_pin.py: ML-DSA-65 public key of the Aegis gateway\n"
            " * (identity sha256 of the key: %s). Do not edit. */\n" % hashlib.sha256(pk).hexdigest())
    f.write("#define AEGIS_GATEWAY_PK { \\\n")
    for i in range(0, len(pk), 16):
        f.write("    " + ", ".join("0x%02x" % b for b in pk[i:i + 16]) + ", \\\n")
    f.write("}\n")
print("wrote", out, "key sha256", hashlib.sha256(pk).hexdigest())
