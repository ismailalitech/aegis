#!/usr/bin/env python3
"""Write a verifier's ML-DSA-65 public key as the C header every endpoint image pins (the STM32 partition, the RW612
TF-M partition and prover, the ZynqMP TA all include endpoints/stm32h573/tfm-aegis-partition/gateway_pk.h), so the
endpoint verifies credentials from that verifier (mutual authentication). An image pins exactly one key: the
verifier named here is the only one that can issue credentials to it; any verifier can still attest it.

  gen_gateway_pin.py GATEWAY_HOST             the gateway's key, from /var/lib/aegis/identity.json over ssh
  gen_gateway_pin.py --identity FILE          a local identity record, e.g. a PC verifier's
                                              (~/.local/state/aegis/identity.json, aegisd.py --platform linux init)
  --sha256-only                               print the key's sha256 (the policy's "verifier_pin_sha256"), write nothing
"""
import argparse
import hashlib
import json
import os
import subprocess
import sys


def main(argv=None):
    ap = argparse.ArgumentParser(description="pin a verifier's ML-DSA-65 key in endpoint firmware")
    ap.add_argument("host", nargs="?", default=os.environ.get("GATEWAY"), help="gateway host (or set GATEWAY)")
    ap.add_argument("--identity", help="a local identity.json instead of the gateway's")
    ap.add_argument("--sha256-only", action="store_true")
    ap.add_argument("--out", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "endpoints",
                                                  "stm32h573", "tfm-aegis-partition", "gateway_pk.h"))
    a = ap.parse_args(argv)
    if a.identity:
        with open(a.identity) as f:
            rec = json.load(f)
        source = a.identity
    elif a.host:
        rec = json.loads(subprocess.run(["ssh", "-o", "BatchMode=yes", "root@" + a.host,
                                         "cat /var/lib/aegis/identity.json"],
                                        check=True, capture_output=True, text=True).stdout)
        source = "root@%s:/var/lib/aegis/identity.json" % a.host
    else:
        ap.error("give the gateway host (or set GATEWAY), or --identity FILE")
    pk = bytes.fromhex(rec["body"]["pk"])
    if len(pk) != 1952:
        sys.exit("%s: not an ML-DSA-65 public key (%d bytes)" % (source, len(pk)))
    digest = hashlib.sha256(pk).hexdigest()
    if a.sha256_only:
        print(digest)
        return 0
    with open(a.out, "w") as f:
        f.write("/* Generated by tools/gen_gateway_pin.py: ML-DSA-65 public key of the Aegis verifier\n"
                " * (sha256 of the key: %s; policy \"verifier_pin_sha256\"). Do not edit. */\n" % digest)
        f.write("#define AEGIS_GATEWAY_PK { \\\n")
        for i in range(0, len(pk), 16):
            f.write("    " + ", ".join("0x%02x" % b for b in pk[i:i + 16]) + ", \\\n")
        f.write("}\n")
    print("wrote", a.out, "key sha256", digest)
    return 0


if __name__ == "__main__":
    sys.exit(main())
