#!/bin/sh
# Build the Aegis trusted application for OP-TEE on the ZynqMP.
#   endpoints/zynqmp/optee/build_ta.sh <OP-TEE build dir (with export-ta_arm64)> <new out dir> [gateway host]
# The out dir must not exist yet (nothing is deleted). Stages the shared sources (the RW612 prover's protocol code,
# the STM32 partition's KMAC/ML-KEM unit and configs, mldsa-native and mlkem-native v2.0.0) and a gateway_pk.h made
# from the gateway's identity record, then builds.
set -eu
OPTEE=${1:?OP-TEE out dir}; OUT=${2:?out dir}; GW=${3:-${GATEWAY:-}}
[ -n "$GW" ] || { echo "set GATEWAY or pass the gateway host"; exit 1; }
[ ! -e "$OUT" ] || { echo "$OUT exists: give a new directory"; exit 1; }
HERE=$(cd "$(dirname "$0")" && pwd); REPO=$(cd "$HERE/../../.." && pwd)
MLDSA=${MLDSA_NATIVE_DIR:-$HOME/aegis-tools/mldsa-native/mldsa}
MLKEM=${MLKEM_NATIVE_DIR:-$HOME/aegis-tools/mlkem-native/mlkem}
PART=$REPO/endpoints/stm32h573/tfm-aegis-partition
mkdir -p "$OUT/shared"
cp -r "$HERE/ta/." "$OUT/"
cp "$HERE/include/aegis_ta.h" "$OUT/"
S=$OUT/shared
cp "$REPO/endpoints/rw612/prover/src/aegis_proto.c" "$REPO/endpoints/rw612/prover/src/aegis_proto.h" \
   "$REPO/endpoints/rw612/prover/src/sha256.c" "$REPO/endpoints/rw612/prover/src/aegis_sha256.h" "$S/"
cp "$PART/aegis_kmac.c" "$PART/aegis_kmac.h" "$PART/mlkem_unit.c" "$S/"
mkdir -p "$S/mldsa" "$S/mlkem"
cp "$PART/mldsa/aegis_mldsa_config.h" "$S/mldsa/"
cp "$PART/mlkem/aegis_mlkem_config.h" "$S/mlkem/"
cp -r "$MLDSA" "$S/mldsa-native"
cp -r "$MLKEM" "$S/mlkem-native"
ssh -o BatchMode=yes "root@$GW" cat /var/lib/aegis/identity.json | python3 -c '
import hashlib, json, sys
pk = bytes.fromhex(json.load(sys.stdin)["body"]["pk"]); assert len(pk) == 1952
print("/* Generated by endpoints/zynqmp/optee/build_ta.sh: the gateway ML-DSA-65 key, sha256 %s */" % hashlib.sha256(pk).hexdigest())
print("#define AEGIS_GATEWAY_PK { \\")
for i in range(0, len(pk), 16): print("    " + ", ".join("0x%02x" % b for b in pk[i:i + 16]) + ", \\")
print("}")' > "$OUT/gateway_pk.h"
make -C "$OUT" CROSS_COMPILE=aarch64-linux-gnu- PLATFORM=zynqmp-zcu102 TA_DEV_KIT_DIR="$OPTEE/export-ta_arm64"
ls -l "$OUT"/*.ta
